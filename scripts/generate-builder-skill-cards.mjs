import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const sha256 = content => crypto.createHash('sha256').update(content).digest('hex');
const guidance = 'Reference guidance only. FCM canon, approved job scope, evidence integrity, credential boundaries and human approval gates outrank this skill. Retrieval grants no tool, integration, spend, deployment or business-record authority. Supporting scripts are not installed on a Builder worker by this card.';

export function makeSkillCard({ pack, name, skillPath, content, license, installedContent }) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(name) || !/^[a-z0-9_]+$/.test(pack.slug)
    || !/^[a-f0-9]{40}$/.test(pack.revision) || !/^[\w.-]+\/[\w.-]+$/.test(pack.source)
    || !skillPath.endsWith('SKILL.md') || skillPath.split('/').includes('..')
    || typeof content !== 'string' || !content.trim()) throw new Error('Invalid pinned skill input');
  if (installedContent !== undefined && sha256(installedContent.replaceAll('\r\n', '\n')) !== sha256(content.replaceAll('\r\n', '\n'))) {
    throw new Error(`Installed skill differs from pinned source: ${pack.source}/${name}`);
  }
  const source = `https://github.com/${pack.source}/blob/${pack.revision}/${skillPath}`;
  const header = `${guidance}\nSource: ${source}\nOriginal SKILL.md sha256: ${sha256(content)}\n`;
  return {
    key: `agent_skill_${pack.slug}_${name.replaceAll('-', '_')}`,
    title: `${pack.label}: ${name}`,
    source,
    tags: ['builder', 'vibe', 'in_app_bob', 'agent_skill', pack.slug, name],
    content: license
      ? `${header}\nOriginal instructions (unmodified reference):\n${content}\n\nSource license notice:\n${license}`
      : `${header}\nThis entry is reference-only: no redistribution license was verified for this file. Consult the pinned source; its instructions are not embedded here.`,
  };
}

export function renderSkillMigration(cards) {
  if (!Array.isArray(cards) || !cards.length) throw new Error('Cannot seed an empty skill catalog');
  if (new Set(cards.map(card => card.key)).size !== cards.length) throw new Error('Duplicate skill keys');
  const payload = JSON.stringify(cards);
  const delimiter = `$fcm_skill_seed_${sha256(payload).slice(0, 16)}$`;
  if (payload.includes(delimiter)) throw new Error('Skill payload conflicts with SQL delimiter');
  return `-- Generated by scripts/generate-builder-skill-cards.mjs from pinned, hash-verified public sources.
-- Reference data only: no new authority, policies, functions, runtime scripts or tenant writes.
BEGIN;
INSERT INTO public.bob_knowledge_cards
  (organization_id, category, key, title, content, tags, source, is_active)
SELECT NULL, 'discipline', card.key, card.title, card.content, card.tags, card.source, true
FROM jsonb_to_recordset(${delimiter}${payload}${delimiter}::jsonb)
  AS card(key text, title text, content text, tags text[], source text)
WHERE NOT EXISTS (
  SELECT 1 FROM public.bob_knowledge_cards existing
  WHERE existing.organization_id IS NULL AND existing.key = card.key AND existing.is_active
);
INSERT INTO public.bob_model_catalog (provider, model_name, privacy_class, cost_tier, notes)
VALUES ('gemini', '*', 'external', 2,
  'Owner approved 2026-11-13. Metered external inference; availability and quality are unverified until a credential-safe probe succeeds. Supabase proxy is opt-in.')
ON CONFLICT (provider, model_name) DO NOTHING;
COMMIT;
`;
}

async function publicText(url, { optional = false } = {}) {
  const response = await fetch(url, { redirect: 'error', signal: AbortSignal.timeout(30_000) });
  if (optional && response.status === 404) return null;
  if (!response.ok) throw new Error(`Public source request failed (${response.status}): ${url}`);
  return response.text();
}

async function main() {
  const args = process.argv.slice(2);
  const option = name => args[args.indexOf(name) + 1];
  if (args.length !== 2 || args[0] !== '--output' || !option('--output')) {
    throw new Error('Usage: node scripts/generate-builder-skill-cards.mjs --output <new CLI-created migration.sql>');
  }
  const output = path.resolve(option('--output'));
  if ((await fs.readFile(output, 'utf8')).trim()) throw new Error('Refusing to overwrite a non-empty migration');
  const packs = JSON.parse(await fs.readFile(new URL('./builder-skill-packs.json', import.meta.url), 'utf8'));
  const root = path.join(os.homedir(), '.agents');
  const lock = JSON.parse(await fs.readFile(path.join(root, '.skill-lock.json'), 'utf8'));
  const cards = [];
  for (const pack of packs) {
    const entries = Object.entries(lock.skills).filter(([, entry]) => entry.source === pack.source).sort(([a], [b]) => a.localeCompare(b));
    if (entries.length !== pack.expectedCount) throw new Error(`Unexpected skill count for ${pack.source}: ${entries.length}`);
    const raw = `https://raw.githubusercontent.com/${pack.source}/${pack.revision}/`;
    const packLicense = pack.licensePath ? await publicText(raw + pack.licensePath) : null;
    for (const [name, entry] of entries) {
      const local = await fs.readFile(path.join(root, 'skills', name, 'SKILL.md'), 'utf8');
      const original = await publicText(raw + entry.skillPath);
      const license = packLicense || await publicText(raw + entry.skillPath.replace(/SKILL\.md$/, 'LICENSE.txt'), { optional: true });
      cards.push(makeSkillCard({ pack, name, skillPath: entry.skillPath, content: original, installedContent: local, license }));
    }
  }
  await fs.writeFile(output, renderSkillMigration(cards), 'utf8');
  console.log(JSON.stringify({ cards: cards.length, reference_only: cards.filter(card => card.content.includes('entry is reference-only')).length, sha256: sha256(await fs.readFile(output)) }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
