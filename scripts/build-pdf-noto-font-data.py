"""Build compact static Noto Sans font data for the Deno PDF renderers."""

import base64
import hashlib
import io
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


FONT_URL = (
    "https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/"
    "NotoSans%5Bwdth%2Cwght%5D.ttf"
)
FONT_SHA256 = "bfb7bb691513f12e734dc346c03a03f784912432d7e3fa8e56efcf906fe86b3d"
FONT_LICENSE_URL = "https://raw.githubusercontent.com/google/fonts/main/ofl/notosans/OFL.txt"
OUTPUT_DIR = Path(__file__).resolve().parents[1] / "supabase/functions/_shared/fonts"
FONT_DATA_PATH = OUTPUT_DIR.parent / "pdf-noto-font-data.ts"
UNICODE_POINTS = (
    set(range(0x20, 0x250))
    | set(range(0x1E00, 0x1F00))
    | set(range(0x2000, 0x2070))
    | set(range(0x20A0, 0x20D0))
    | set(range(0x2100, 0x2150))
)


def download(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "FCM-PDF-Font-Builder"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def static_subset(variable_font_data: bytes, weight: int) -> bytes:
    variable_font = TTFont(io.BytesIO(variable_font_data))
    static_font = instantiateVariableFont(
        variable_font,
        {"wght": weight, "wdth": 100},
        inplace=False,
    )
    options = subset.Options()
    options.flavor = None
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=UNICODE_POINTS)
    subsetter.subset(static_font)
    output = io.BytesIO()
    static_font.save(output)
    return output.getvalue()


def main() -> None:
    source = download(FONT_URL)
    actual_hash = hashlib.sha256(source).hexdigest()
    if actual_hash != FONT_SHA256:
        raise RuntimeError(f"Unexpected Google Fonts source checksum: {actual_hash}")

    regular = static_subset(source, 400)
    bold = static_subset(source, 700)
    license_text = download(FONT_LICENSE_URL).decode("utf-8")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "OFL.txt").write_text(license_text, encoding="utf-8")

    module = """// Generated by scripts/build-pdf-noto-font-data.py; do not edit by hand.
const regularBase64 = "{regular}";
const boldBase64 = "{bold}";

function decodeFont(data: string): Uint8Array {{
  const binary = atob(data);
  return Uint8Array.from(binary, (character) => character.charCodeAt(0));
}}

export function pdfNotoFontBytes() {{
  return {{ normal: decodeFont(regularBase64), bold: decodeFont(boldBase64) }};
}}
""".format(
        regular=base64.b64encode(regular).decode("ascii"),
        bold=base64.b64encode(bold).decode("ascii"),
    )
    FONT_DATA_PATH.write_text(module, encoding="ascii")
    print(
        f"Generated static fonts ({len(regular)} + {len(bold)} bytes); "
        f"module {FONT_DATA_PATH.stat().st_size} bytes"
    )


if __name__ == "__main__":
    main()