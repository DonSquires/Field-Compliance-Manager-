const fs = require('node:fs');
const path = require('node:path');
const Holidays = require('date-holidays');

const regions = ['AUK','BOP','CAN','CIT','GIS','HKB','MBH','MWT','NSN','NTL','OTA','STL','TAS','TKI','WKO','WGN','WTC'];
const years = Array.from({ length: 36 }, (_, index) => 2020 + index);
const publicDates = (calendar, year) => calendar.getHolidays(year).filter((holiday) => holiday.type === 'public').map((holiday) => [holiday.date.slice(0, 10), holiday.name]);
const nationalCalendar = new Holidays('NZ');
const national = Object.fromEntries(years.map((year) => [year, publicDates(nationalCalendar, year)]));
const regional = Object.fromEntries(regions.map((region) => {
  const calendar = new Holidays('NZ', region);
  return [region, Object.fromEntries(years.map((year) => {
    const nationalKeys = new Set(national[year].map(([date, name]) => `${date}|${name}`));
    return [year, publicDates(calendar, year).filter(([date, name]) => !nationalKeys.has(`${date}|${name}`))];
  }))];
}));
const output = `// Generated by scripts/generate-nz-holidays.cjs using date-holidays. Do not edit manually.\nexport const NZ_NATIONAL_HOLIDAYS: Record<number, Array<[string, string]>> = ${JSON.stringify(national)};\nexport const NZ_REGIONAL_HOLIDAYS: Record<string, Record<number, Array<[string, string]>>> = ${JSON.stringify(regional)};\n`;
fs.writeFileSync(path.resolve(__dirname, '../src/lib/nzHolidays.generated.ts'), output);