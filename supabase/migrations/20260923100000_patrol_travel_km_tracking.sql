-- The R&M patrol-log import (2026-09-23, 14 clients) captures each real
-- recorded per-visit travel distance ("Job Kms"/"Job KMs" column - the
-- officer's own recorded figure, not a GPS estimate) into a payload JSONB
-- blob only. Confirmed via Atlas (bob_atlas_flow_reach downstream from both
-- tables returned zero edges) that nothing reads it back out - the real
-- vehicle-usage / cost-of-service tracking the owner intended never happens.
-- This promotes it to a real, queryable column, matching the existing
-- dispatch_job_pay_lines.distance_km name/precision convention.
--
-- Distinct from shift_stops.travel_distance_metres, which is a pre-visit
-- ESTIMATE generated by the live patrol engine at shift-publish time, not an
-- actual recorded distance - no actual-travel counterpart exists there yet.
ALTER TABLE public.observations ADD COLUMN IF NOT EXISTS distance_km numeric(10,3);
COMMENT ON COLUMN public.observations.distance_km IS 'Real recorded travel distance for this patrol visit (officer-recorded, e.g. from a patrol-log import or future manual/odometer entry). Not a GPS estimate - see shift_stops.travel_distance_metres for the live patrol engine''s pre-visit estimate.';

ALTER TABLE public.location_events ADD COLUMN IF NOT EXISTS distance_km numeric(10,3);
COMMENT ON COLUMN public.location_events.distance_km IS 'Real recorded travel distance for this patrol visit (officer-recorded, e.g. from a patrol-log import or future manual/odometer entry). Not a GPS estimate - see shift_stops.travel_distance_metres for the live patrol engine''s pre-visit estimate.';

-- Backfill from the already-imported historical payload (rm_patrol_log_import rows only).
UPDATE public.observations
SET distance_km = NULLIF(external_refs->'import'->>'job_kms', '')::numeric
WHERE external_refs->'import'->>'source' = 'rm_patrol_log_import'
  AND distance_km IS NULL
  AND external_refs->'import'->>'job_kms' ~ '^\d+(\.\d+)?$';

UPDATE public.location_events
SET distance_km = NULLIF(payload->>'job_kms', '')::numeric
WHERE payload->>'source' = 'rm_patrol_log_import'
  AND distance_km IS NULL
  AND payload->>'job_kms' ~ '^\d+(\.\d+)?$';

-- Read-only summary for "cost of service and vehicle usage" reporting - real km
-- driven per officer, grouped by organisation/client-site/zone/month. No write
-- path into finance_service_costs/P&L here (a separate, financial-integrity
-- decision the owner has not yet made for historical data).
CREATE OR REPLACE VIEW public.patrol_travel_km_summary AS
SELECT organization_id, officer_id, zone_id, site_id, date_trunc('month', observed_at) AS month,
       count(*) AS visit_count, sum(distance_km) AS total_distance_km
FROM public.observations
WHERE distance_km IS NOT NULL
GROUP BY organization_id, officer_id, zone_id, site_id, date_trunc('month', observed_at)
UNION ALL
SELECT organization_id, observed_entity_id AS officer_id, zone_id, client_site_id AS site_id, date_trunc('month', occurred_at) AS month,
       count(*) AS visit_count, sum(distance_km) AS total_distance_km
FROM public.location_events
WHERE distance_km IS NOT NULL AND observed_entity_type = 'staff'
GROUP BY organization_id, observed_entity_id, zone_id, client_site_id, date_trunc('month', occurred_at);
COMMENT ON VIEW public.patrol_travel_km_summary IS 'Real recorded travel km per officer/place/month, unioned from observations and location_events.distance_km. Read-only reporting aggregate for cost-of-service and vehicle-usage tracking - not part of the finance/invoicing write pipeline.';
GRANT SELECT ON public.patrol_travel_km_summary TO authenticated, service_role;
