/**
 * send-invoice — email an admin invoice to the client via SMTP
 *
 * POST /functions/v1/send-invoice
 * Body: { invoice_id, to }  (to optional — falls back to the client org's
 *        primary billing contact ONLY when the invoice row carries
 *        client_organization_id; the legacy admin shape usually does not,
 *        so `to` is effectively required there.)
 *
 * Auth: valid JWT from an admin/master/grand_master user in the invoice's org.
 *
 * Mirrors send-report-pack. Sends an HTML invoice summary via the configured
 * SMTP, then marks the invoice status='sent' and stamps sent_at.
 *
 * Schema: uses the LIVE invoices columns (verified 2026-06-28): invoice_number,
 * client_organization_id, total_amount, currency, status, invoice_date,
 * due_date, notes, sent_at. (There is NO client_name/amount/issued_at/due_at.)
 * Client name is derived from organizations; recipient falls back to the
 * client org's primary crm_contacts email.
 *
 * Required edge-function secrets (Supabase → Edge Functions → Secrets):
 *   SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASS, SMTP_FROM
 * If any are missing the function returns a clear 'SMTP not configured'
 * error — it never silently succeeds.
 */ import { serve } from 'https://deno.land/std@0.168.0/http/server.ts';
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2';
import { SMTPClient } from 'https://deno.land/x/denomailer@1.6.0/mod.ts';
const SUPABASE_URL = Deno.env.get('SUPABASE_URL') ?? '';
const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') ?? '';
const SUPABASE_ANON_KEY = Deno.env.get('SUPABASE_ANON_KEY') ?? '';
const SMTP_HOST = Deno.env.get('SMTP_HOST') ?? '';
const SMTP_PORT = Number(Deno.env.get('SMTP_PORT') ?? '587');
const SMTP_USER = Deno.env.get('SMTP_USER') ?? '';
const SMTP_PASS = Deno.env.get('SMTP_PASS') ?? '';
const SMTP_FROM = Deno.env.get('SMTP_FROM') ?? SMTP_USER;
const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type'
};
const CAN_SEND = [
  'grand_master',
  'master',
  'admin'
];
function money(amount, currency) {
  const n = amount == null ? null : Number(amount);
  const ccy = String(currency ?? 'NZD');
  return n == null || Number.isNaN(n) ? '—' : `${ccy} ${n.toFixed(2)}`;
}
function fmtDate(v) {
  if (!v) return '—';
  const d = new Date(String(v));
  return Number.isNaN(d.getTime()) ? '—' : d.toISOString().slice(0, 10);
}
function invoiceHtml(inv, clientName) {
  return `
    <div style="font-family: Georgia, serif; color: #111; max-width: 640px;">
      <h2 style="margin:0 0 4px;">TAX INVOICE</h2>
      <div style="font-size:13px; color:#555;">Iron Eagle Security</div>
      <hr style="border:0; border-top:1px solid #ddd; margin:12px 0;" />
      <table style="font-size:13px; border-collapse:collapse;">
        <tr><td style="color:#555; padding:2px 12px 2px 0;">Invoice number</td><td><strong>${inv.invoice_number ?? '—'}</strong></td></tr>
        <tr><td style="color:#555; padding:2px 12px 2px 0;">Client</td><td>${clientName}</td></tr>
        <tr><td style="color:#555; padding:2px 12px 2px 0;">Invoice date</td><td>${fmtDate(inv.invoice_date)}</td></tr>
        <tr><td style="color:#555; padding:2px 12px 2px 0;">Due</td><td>${fmtDate(inv.due_date)}</td></tr>
      </table>
      <div style="font-size:18px; font-weight:bold; margin:16px 0;">Amount due: ${money(inv.total_amount, inv.currency)}</div>
      ${inv.notes ? `<div style="font-size:13px; color:#333;"><strong>Notes:</strong> ${inv.notes}</div>` : ''}
      <hr style="border:0; border-top:1px solid #ddd; margin:16px 0;" />
      <div style="font-size:11px; color:#888; font-style:italic;">Generated by Field Compliance Manager.</div>
    </div>
  `;
}
serve(async (req)=>{
  if (req.method === 'OPTIONS') return new Response('ok', {
    headers: CORS
  });
  const json = (body, status = 200)=>new Response(JSON.stringify(body), {
      status,
      headers: {
        ...CORS,
        'Content-Type': 'application/json'
      }
    });
  try {
    const authHeader = req.headers.get('Authorization') ?? '';
    const callerClient = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
      global: {
        headers: {
          Authorization: authHeader
        }
      }
    });
    const { data: { user: caller }, error: authError } = await callerClient.auth.getUser();
    if (authError || !caller) return json({
      error: 'Unauthorized'
    }, 401);
    const admin = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);
    const { data: callerProfile } = await admin.from('user_profiles').select('role, organization_id').eq('id', caller.id).single();
    if (!callerProfile || !CAN_SEND.includes(callerProfile.role)) {
      return json({
        error: 'Forbidden: insufficient role'
      }, 403);
    }
    const body = await req.json();
    if (!body.invoice_id) return json({
      error: 'invoice_id is required'
    }, 400);
    // Load the invoice (live columns) and verify org.
    const { data: inv } = await admin.from('invoices').select('id, organization_id, client_organization_id, invoice_number, total_amount, currency, status, invoice_date, due_date, notes').eq('id', body.invoice_id).single();
    if (!inv) return json({
      error: 'Invoice not found'
    }, 404);
    if (callerProfile.role !== 'grand_master' && inv.organization_id !== callerProfile.organization_id) {
      return json({
        error: 'Cannot send invoices for other organizations'
      }, 403);
    }
    // Client name (derived) + recipient fallback from the client org's primary contact.
    let clientName = 'Client';
    let recipient = body.to ?? '';
    if (inv.client_organization_id) {
      const { data: clientOrg } = await admin.from('organizations').select('name').eq('id', inv.client_organization_id).maybeSingle();
      if (clientOrg?.name) clientName = String(clientOrg.name);
      if (!recipient) {
        const { data: contact } = await admin.from('crm_contacts').select('email').eq('organization_id', inv.client_organization_id).eq('is_primary', true).not('email', 'is', null).maybeSingle();
        recipient = contact?.email ?? '';
      }
    }
    if (!recipient) return json({
      error: 'No recipient email (pass `to`, or set a primary contact on the client organisation)'
    }, 400);
    // Guard: SMTP must be configured.
    if (!SMTP_HOST || !SMTP_USER || !SMTP_PASS) {
      return json({
        error: 'SMTP not configured (set SMTP_HOST, SMTP_USER, SMTP_PASS, SMTP_FROM secrets)'
      }, 503);
    }
    // Send via SMTP.
    try {
      const client = new SMTPClient({
        connection: {
          hostname: SMTP_HOST,
          port: SMTP_PORT,
          tls: SMTP_PORT === 465,
          auth: {
            username: SMTP_USER,
            password: SMTP_PASS
          }
        }
      });
      await client.send({
        from: SMTP_FROM,
        to: recipient,
        subject: `Invoice ${inv.invoice_number ?? ''} — Iron Eagle Security`.trim(),
        html: invoiceHtml(inv, clientName)
      });
      await client.close();
    } catch (sendErr) {
      const msg = sendErr instanceof Error ? sendErr.message : 'SMTP send failed';
      return json({
        error: 'Send failed',
        details: msg
      }, 502);
    }
    // Record delivery using real columns: status + sent_at.
    const nextStatus = inv.status === 'paid' || inv.status === 'void' ? inv.status : 'sent';
    await admin.from('invoices').update({
      status: nextStatus,
      sent_at: new Date().toISOString()
    }).eq('id', inv.id);
    return json({
      success: true,
      sent_to: recipient,
      status: nextStatus
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : 'Internal error';
    return json({
      error: 'Server error',
      details: msg
    }, 500);
  }
});
