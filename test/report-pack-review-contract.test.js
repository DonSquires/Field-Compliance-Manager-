  assert.match(pdf, /embedPdfNotoFonts\(pdf\)/);
  assert.match(pdf, /pdfTextFontRuns/);
  assert.match(pdfFonts, /registerFontkit\(fontkit\)/);
  assert.match(pdfFonts, /pdfNotoFontBytes\(\)/);
  assert.match(pdfFontData, /Generated by scripts\/build-pdf-noto-font-data\.py/);
  assert.match(pdf, /p_expected_updated_at: pack\.updated_at/);
  assert.match(pdf, /rpc\('record_report_pack_pdf'/);
  assert.match(pdf, /agreementName: reportAgreementName\(pack\)/);
  assert.match(pdf, /remove\(\[path\]\)/);
  assert.match(pdf, /remove\(\[pack\.pdf_path\]\)/);
  assert.match(pdf, /pdfTextWidth\(text, fonts, size\)/);
