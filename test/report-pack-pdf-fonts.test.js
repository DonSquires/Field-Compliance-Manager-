const assert = require('node:assert/strict');
const test = require('node:test');

test('PDF text selects Latin subsets per character and visibly replaces unsupported glyphs', async () => {
  const { pdfTextFontRuns } = await import('../supabase/functions/_shared/pdf-text-fonts.mjs');
  const latinFont = { name: 'latin' };
  const latinExtendedFont = { name: 'latin-ext' };
  const latinCodePoints = new Set(Array.from({ length: 128 }, (_, codePoint) => codePoint));
  const latinExtendedCodePoints = new Set([0x0101, 0x2014]);

  const runs = pdfTextFontRuns('FCM M\u0101ori \u2014 report \u{1F600}', latinFont, latinExtendedFont, latinCodePoints, latinExtendedCodePoints);

  assert.deepEqual(runs.map((run) => ({ text: run.text, font: run.font.name })), [
    { text: 'FCM M', font: 'latin' },
    { text: '\u0101', font: 'latin-ext' },
    { text: 'ori ', font: 'latin' },
    { text: '\u2014', font: 'latin-ext' },
    { text: ' report ?', font: 'latin' },
  ]);
});

test('PDF wrapping measures glyph widths and preserves long words and extended characters', async () => {
  const { pdfTextWidth, wrapPdfText } = await import('../supabase/functions/_shared/pdf-text-fonts.mjs');
  const makeFont = (name) => ({
    name,
    widthOfTextAtSize: (text) => Array.from(text).length,
  });
  const latinFont = makeFont('latin');
  const latinExtendedFont = makeFont('latin-ext');
  const fonts = {
    latin: latinFont,
    latinExtended: latinExtendedFont,
    latinCodePoints: new Set(Array.from({ length: 128 }, (_, codePoint) => codePoint)),
    latinExtendedCodePoints: new Set([0x0101, 0x2014]),
  };
  const source = 'M\u0101ori—long-unbroken-value';
  const lines = wrapPdfText(source, fonts, 1, 9);

  assert.equal(lines.join(''), source);
  assert.ok(lines.every((line) => pdfTextWidth(line, fonts, 1) <= 9));
  assert.ok(lines.some((line) => line.includes('\u0101')));
  assert.ok(lines.some((line) => line.includes('\u2014')));
  assert.deepEqual(wrapPdfText('M\u0101ori evidence', fonts, 1, 9), ['M\u0101ori', 'evidence']);
});

test('PDF font strategy uses prebuilt static TTFs without request-time WOFF processing', async () => {
  const { readFileSync } = require('node:fs');
  const { resolve } = require('node:path');
  const fonts = readFileSync(resolve(__dirname, '../supabase/functions/_shared/pdf-noto-fonts.ts'), 'utf8');
  const fontData = readFileSync(resolve(__dirname, '../supabase/functions/_shared/pdf-noto-font-data.ts'), 'utf8');
  const report = readFileSync(resolve(__dirname, '../supabase/functions/generate-report-pack-pdf/index.ts'), 'utf8');

  assert.match(fonts, /pdfNotoFontBytes\(\)/);
  assert.match(fonts, /pdf\.embedFont\(fontBytes\.normal, \{ subset: false \}\)/);
  assert.match(fonts, /pdf\.embedFont\(fontBytes\.bold, \{ subset: false \}\)/);
  assert.match(fonts, /pdfTextFontPair\(latinNormal, latinNormal\)/);
  assert.match(report, /embedPdfNotoFonts\(pdf\)/);
  assert.match(fontData, /Generated by scripts\/build-pdf-noto-font-data\.py/);
  assert.match(fontData, /Uint8Array\.from\(binary/);
  assert.doesNotMatch(fonts, /fetch\(fontUrl\)/);
  assert.doesNotMatch(report, /fetch\(fontUrl\)/);
});